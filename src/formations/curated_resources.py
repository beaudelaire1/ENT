LANGUAGE_LABELS = {"fr": "Français", "en": "Anglais"}


@dataclass(frozen=True, slots=True)
class CuratedResource:
    key: str
    title: str
    url: str
    provider: str
    purpose: str
    role: str
    language: str
    format_label: str
    description: str

    @property
    def role_label(self) -> str:
        return ROLE_LABELS[self.role]

    @property
    def language_label(self) -> str:
        return LANGUAGE_LABELS[self.language]


@dataclass(frozen=True, slots=True)
class TopicRule:
    units: tuple[str, ...]
    terms: tuple[str, ...]
    resources: tuple[str, ...]


def _resource(
    key: str,
    title: str,
    url: str,
    provider: str,
    purpose: str,
    role: str,
    language: str,
    format_label: str,
    description: str,
) -> CuratedResource:
    return CuratedResource(key, title, url, provider, purpose, role, language, format_label, description)



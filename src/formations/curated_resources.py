def _normalise(value: str) -> str:
    decomposed = unicodedata.normalize("NFKD", value)
    return "".join(character for character in decomposed if not unicodedata.combining(character)).casefold()


def recommendations_for(title: str, unit_titles: list[str] | tuple[str, ...]) -> list[CuratedResource]:
    """Retourne un parcours court, ordonné et sans doublon pour une compétence."""
    keys: list[str] = []
    for unit_title in unit_titles:
        keys.extend(UNIT_BUNDLES.get(unit_title, ()))

    normalised_title = _normalise(title)
    units = set(unit_titles)
    for rule in TOPIC_RULES:
        if units.intersection(rule.units) and any(term in normalised_title for term in rule.terms):
            keys.extend(rule.resources)

    unique_keys = list(dict.fromkeys(keys))
    return [RESOURCES[key] for key in unique_keys]


def recommendations_for_competency(competency) -> list[CuratedResource]:
    """Adapte la fonction pure à un objet ``Competency`` déjà chargé ou ordinaire."""
    unit_titles = list(competency.units.values_list("title", flat=True))
    return recommendations_for(competency.title, unit_titles)
